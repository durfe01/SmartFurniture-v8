export function cloneCatalogFurniture(id: string): {
  spec: CatalogFurnitureSpec;
  topology: FurnitureTopology;
  params: ScaleAndBoardParams;
} | null {
  const found = CATALOG_14_MUEBLES.find((c) => c.id === id);
  if (!found) return null;
  const clonedQuadNorm = found.initialQuadNorm
    ? (found.initialQuadNorm.map((p) => ({ ...p })) as [Point2D, Point2D, Point2D, Point2D])
    : undefined;
  return {
    spec: {
      ...found,
      initialQuadNorm: clonedQuadNorm,
    },
    topology: {
      ...found.topology,
      vDividers: found.topology.vDividers.map((d) => ({ ...d })),
      hShelves: found.topology.hShelves.map((s) => ({ ...s })),
      diagonalDividers: found.topology.diagonalDividers
        ? found.topology.diagonalDividers.map((diag) => ({ ...diag }))
        : undefined,
      frontZones: (found.topology.frontZones ?? []).map((z) => ({ ...z })),
      hardwareItems: (found.topology.hardwareItems ?? []).map((h) => ({ ...h })),
    },
    params: {
      ...found.params,
      targetDimensions: { ...found.params.targetDimensions },
      referenceDimensions: { ...found.params.referenceDimensions },
      sheetDimensions: { ...found.params.sheetDimensions },
      backPanelSheetDimensions: found.params.backPanelSheetDimensions
        ? { ...found.params.backPanelSheetDimensions }
        : undefined,
      costConfig: found.params.costConfig ? { ...found.params.costConfig } : undefined,
    },
  };
}
